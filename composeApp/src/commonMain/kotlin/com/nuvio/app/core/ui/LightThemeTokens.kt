package com.nuvio.app.core.ui

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

private val LightDanger = Color(0xFFB3261E)

internal fun lightNuvioColorScheme(palette: ThemeColorPalette): ColorScheme = lightColorScheme(
    primary = palette.secondary,
    onPrimary = palette.onSecondary,
    primaryContainer = palette.focusBackground,
    onPrimaryContainer = LightNeutrals.textPrimary,
    secondary = palette.secondaryVariant,
    onSecondary = palette.onSecondaryVariant,
    secondaryContainer = palette.focusBackground,
    onSecondaryContainer = LightNeutrals.textPrimary,
    tertiary = palette.secondaryVariant,
    onTertiary = palette.onSecondaryVariant,
    background = palette.background,
    onBackground = LightNeutrals.textPrimary,
    surface = palette.backgroundElevated,
    onSurface = LightNeutrals.textPrimary,
    surfaceVariant = palette.backgroundCard,
    onSurfaceVariant = LightNeutrals.textSecondary,
    surfaceTint = palette.secondary,
    surfaceBright = palette.backgroundElevated,
    surfaceDim = palette.backgroundCard,
    surfaceContainerLowest = LightNeutrals.surface,
    surfaceContainerLow = palette.backgroundElevated,
    surfaceContainer = palette.backgroundElevated,
    surfaceContainerHigh = palette.backgroundElevated,
    surfaceContainerHighest = palette.backgroundCard,
    inverseSurface = Color(0xFF22261F),
    inverseOnSurface = Color(0xFFF1EDE6),
    inversePrimary = palette.focusBackground,
    outline = LightNeutrals.borderStrong,
    outlineVariant = LightNeutrals.borderDefault,
    error = LightDanger,
    onError = Color.White,
    errorContainer = Color(0xFFF9DEDC),
    onErrorContainer = Color(0xFF410E0B),
    scrim = Color.Black,
)

internal fun lightNuvioColorTokens(
    palette: ThemeColorPalette,
    dark: NuvioColorTokens,
): NuvioColorTokens = dark.copy(
    background = palette.background,
    surface = palette.backgroundElevated,
    surfaceElevated = palette.backgroundElevated,
    surfaceCard = palette.backgroundCard,
    surfaceSheet = palette.backgroundElevated,
    surfaceDialog = palette.backgroundElevated,
    surfacePopover = palette.backgroundElevated,
    nativeChrome = palette.background,
    textPrimary = LightNeutrals.textPrimary,
    textSecondary = LightNeutrals.textSecondary,
    textMuted = LightNeutrals.textMuted,
    textDisabled = LightNeutrals.textMuted.copy(alpha = NuvioTokens.Opacity.disabled),
    textInverse = Color(0xFFF1EDE6),
    accent = palette.secondary,
    accentStrong = palette.secondaryVariant,
    onAccent = palette.onSecondary,
    focusRing = palette.focusRing,
    focusBackground = palette.focusBackground,
    borderSubtle = LightNeutrals.textPrimary.copy(alpha = 0.10f),
    borderDefault = LightNeutrals.borderDefault,
    borderStrong = LightNeutrals.borderStrong,
    borderFocus = palette.focusRing,
    borderSelected = palette.secondary.copy(alpha = NuvioTokens.Opacity.strong),
    success = Color(0xFF2F6B28),
    warning = Color(0xFF7D5700),
    danger = LightDanger,
    info = Color(0xFF285F6C),
    neutral = LightNeutrals.textMuted,
    overlayScrim = Color.Black.copy(alpha = 0.40f),
    overlayHover = Color.Black.copy(alpha = 0.05f),
    overlayPressed = Color.Black.copy(alpha = 0.08f),
    overlaySelected = Color.Black.copy(alpha = 0.10f),
    overlayDisabled = Color.White.copy(alpha = 0.50f),
    shimmer = Color.Black.copy(alpha = 0.06f),
    skeleton = Color.Black.copy(alpha = 0.05f),
)
